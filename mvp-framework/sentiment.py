"""
职坐标数字人框架 - 情感分析
基于关键词的情感分析，输出 -2 ~ +2 的情感值。
前端根据该值驱动表情与动作（当无 Action 匹配时作为回退）。
"""
import re

# 积极词（命中加分）
POSITIVE_WORDS = {
    "好": 0.4, "棒": 0.6, "太好了": 1.0, "成功": 1.2, "谢谢": 0.5,
    "感谢": 0.5, "开心": 0.8, "喜欢": 0.6, "厉害": 0.9, "恭喜": 1.2,
    "真棒": 1.0, "点赞": 0.8, "欢迎": 0.5, "没问题": 0.5, "当然": 0.4,
    "好的": 0.3, "可以": 0.3, "对": 0.2, "是": 0.1, "加油": 0.6,
}

# 消极词（命中减分）
NEGATIVE_WORDS = {
    "不好": -0.6, "失败": -1.2, "抱歉": -0.5, "对不起": -0.6, "难过": -1.0,
    "不行": -0.7, "错误": -0.8, "不行": -0.7, "不能": -0.5, "不可以": -0.6,
    "遗憾": -0.8, "失望": -0.9, "抱歉不行": -0.8, "小心": -0.2, "危险": -0.6,
    "警告": -0.5, "麻烦": -0.3, "问题": -0.2,
}


def analyze_sentiment(text):
    """
    分析文本情感值。
    :param text: 文本
    :return: 情感值 [-2, 2]
    """
    score = 0.0
    for word, val in POSITIVE_WORDS.items():
        if word in text:
            score += val
    for word, val in NEGATIVE_WORDS.items():
        if word in text:
            score += val
    # 限制在 [-2, 2]
    return round(max(-2.0, min(2.0, score)), 2)


if __name__ == "__main__":
    for t in ["太好了，成功了！", "抱歉，这个我不太清楚", "欢迎来到职坐标"]:
        print(t, "->", analyze_sentiment(t))
